// Generates supabase/seed.sql from src/data/catalog.json (v2).
// Run: npx tsx scripts/gen-seed.ts
import { writeFileSync } from 'node:fs'
import catalog from '../src/data/catalog.json'

const esc = (s: string) => s.replace(/'/g, "''")
const S = (v: string | null | undefined) => (v == null || v === '' ? 'null' : `'${esc(v)}'`)
const N = (v: number | null | undefined) => (v == null ? 'null' : String(v))
const J = (v: unknown) => `'${esc(JSON.stringify(v ?? null))}'::jsonb`

const out: string[] = []
out.push('-- GENERATED by scripts/gen-seed.ts from src/data/catalog.json. Do not edit by hand.')
out.push('-- Run in the Supabase SQL editor AFTER schema.sql. Upserts every product; leaves responses untouched.\n')
const COLS = 'id, category, name_zh, name_en, type_zh, type_en, url, image_url, price_twd, bullets_zh, bullets_en, match, material, style, sort_order, active'
out.push(`insert into products (${COLS}) values`)
const rows = catalog.map((p) => `  (${[
  S(p.id), S(p.category), S(p.name_zh), S(p.name_en), S(p.type_zh), S(p.type_en), S(p.url), S(p.image_url),
  N(p.price_twd as number | null), J(p.bullets_zh), J(p.bullets_en), J(p.match),
  S((p as { material?: string }).material ?? null), S((p as { style?: string }).style ?? null),
  N(p.sort_order), String(p.active !== false),
].join(', ')})`)
out.push(rows.join(',\n'))
out.push(`on conflict (id) do update set
  category = excluded.category, name_zh = excluded.name_zh, name_en = excluded.name_en,
  type_zh = excluded.type_zh, type_en = excluded.type_en, url = excluded.url, image_url = excluded.image_url,
  price_twd = excluded.price_twd, bullets_zh = excluded.bullets_zh, bullets_en = excluded.bullets_en,
  match = excluded.match, material = excluded.material, style = excluded.style,
  sort_order = excluded.sort_order, active = excluded.active;`)
writeFileSync('supabase/seed.sql', out.join('\n') + '\n')
console.log(`seed.sql: ${catalog.length} products`)
